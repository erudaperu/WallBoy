"""Export this small MLP to readable JSON and dependency-free C++17."""
import json
from pathlib import Path
import random

import torch
from torch import nn

from .agent import load_policy, q_values
from .env import OBSERVATIONS, Runner


def export_policy(checkpoint, output):
    torch.set_num_threads(1)
    model, config, metadata = load_policy(checkpoint)
    out = Path(output)
    out.mkdir(parents=True, exist_ok=True)
    layers = [{"weight": layer.weight.detach().tolist(), "bias": layer.bias.detach().tolist()}
              for layer in model.layers if isinstance(layer, nn.Linear)]
    data = {"format_version": 1, "architecture": [7, model.hidden_size, model.hidden_size, 2],
            "activation": "ReLU after the first two layers; linear final layer",
            "weight_layout": "weight[output_neuron][input_neuron]",
            "observations": OBSERVATIONS, "actions": ["wait", "jump"],
            "physics_hz": 60, "decision_every_ticks": config.action_ticks,
            "environment": vars(config), "checkpoint_metadata": metadata, "layers": layers}
    (out / "policy.json").write_text(json.dumps(data, indent=2))
    header = ["// Generated by Wallboy AI Rival. All inference is learned matrix math.",
              "#pragma once", "#include <array>", "#include <algorithm>",
              "namespace wallboy_ai {", "using Observation = std::array<float, 7>;",
              "inline constexpr int action_ticks = " + str(config.action_ticks) + ";"]
    for i, layer in enumerate(layers):
        values = [v for row in layer["weight"] for v in row]
        for name, sequence in ((f"w{i}", values), (f"b{i}", layer["bias"])):
            formatted = [format(v, ".9e") + "f" for v in sequence]
            header.append(f"inline constexpr std::array<float, {len(sequence)}> {name} = {{")
            header.extend("  " + ", ".join(formatted[j:j+8]) + "," for j in range(0, len(sequence), 8))
            header.append("};")
    header.append("""
template <std::size_t In, std::size_t Out>
inline std::array<float, Out> dense(const std::array<float, In>& x,
    const std::array<float, In * Out>& w, const std::array<float, Out>& b, bool relu) {
    std::array<float, Out> y{};
    for (std::size_t o = 0; o < Out; ++o) {
        float sum = b[o];
        for (std::size_t i = 0; i < In; ++i) sum += w[o * In + i] * x[i];
        y[o] = relu ? std::max(0.0f, sum) : sum;
    }
    return y;
}
inline std::array<float, 2> q_values(const Observation& observation) {
    const auto a = dense<7, 64>(observation, w0, b0, true);
    const auto b = dense<64, 64>(a, w1, b1, true);
    return dense<64, 2>(b, w2, b2, false);
}
inline int action(const Observation& observation) {
    const auto q = q_values(observation);
    return q[1] > q[0] ? 1 : 0; // Same first-index tie break as PyTorch argmax.
}
} // namespace wallboy_ai
""")
    (out / "policy.hpp").write_text("\n".join(header).replace("<7, 64>", f"<7, {model.hidden_size}>").replace("<64, 64>", f"<{model.hidden_size}, {model.hidden_size}>").replace("<64, 2>", f"<{model.hidden_size}, 2>"))
    # Fixtures cover actual reachable states under both greedy and random play.
    rng = random.Random(17)
    samples = []
    env = Runner(config)
    for episode in range(20):
        observation = env.reset(40_000 + episode)
        while not env.done:
            values = q_values(model, observation)
            action = int(values.argmax())
            samples.append(observation + values.tolist() + [action])
            observation, _, _, _ = env.step(action if episode % 2 == 0 else rng.randrange(2))
    with (out / "parity.tsv").open("w") as handle:
        for sample in samples:
            handle.write("\t".join(str(value) for value in sample) + "\n")
    print(f"Exported learned weights, policy.hpp and {len(samples)} parity fixtures to {out}")
